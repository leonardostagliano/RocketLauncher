// Genera THIRD-PARTY-LICENSES.txt (npm run licenses): il testo delle licenze di tutto il materiale di terzi che
// finisce nei file distribuiti. Prima Inter e Lucide dell'interfaccia (da THIRD-PARTY-NOTICES.md e OFL.txt), poi
// i crate Rust compilati nell'eseguibile per Windows x64, con i file di licenza che ciascun crate pubblica.
// I crate vengono da `cargo metadata --locked` per il target Windows x64: le dipendenze normali raggiungibili dal
// crate dell'app, esclusi build-dependencies, dev-dependencies e macro procedurali (girano solo in compilazione).
// La prima riga di dati registra l'impronta degli input: tests/third-party-licenses.test.mjs la ricalcola e fallisce
// se Cargo.lock o le note sono cambiati senza rigenerare il file. La release lo pubblica accanto agli eseguibili.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const licensesFile = 'THIRD-PARTY-LICENSES.txt'
export const rustTarget = 'x86_64-pc-windows-msvc'
export const licenseInputs = ['src-tauri/Cargo.lock', 'THIRD-PARTY-NOTICES.md', 'src/assets/fonts/OFL.txt']

const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-_.].*)?$/i
const RULE = '-'.repeat(80)

/** Testo con fine riga LF e senza spazi in coda: lo stesso file dà la stessa impronta con checkout CRLF o LF. */
export function normalizeText(text) {
  return text.replace(/^﻿/, '').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim()
}

/** Impronta SHA-256 degli input (Cargo.lock, note di terze parti, licenza di Inter), indipendente dai fine riga. */
export function inputsFingerprint(root) {
  const hash = createHash('sha256')
  for (const file of licenseInputs) hash.update(`${file}\n${normalizeText(readFileSync(join(root, file), 'utf8'))}\n`)
  return hash.digest('hex')
}

/** I pacchetti linkati nell'eseguibile: dipendenze normali dal crate radice, senza entrare nelle macro procedurali. */
export function runtimePackages(metadata) {
  const packages = new Map(metadata.packages.map((pkg) => [pkg.id, pkg]))
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]))
  const isProcMacro = (pkg) => pkg.targets.some((target) => target.kind.includes('proc-macro'))
  const root = metadata.resolve.root
  const seen = new Set([root])
  const stack = [root]
  while (stack.length > 0) {
    for (const dep of nodes.get(stack.pop()).deps) {
      if (seen.has(dep.pkg) || !dep.dep_kinds.some((kind) => kind.kind === null)) continue
      if (isProcMacro(packages.get(dep.pkg))) continue
      seen.add(dep.pkg)
      stack.push(dep.pkg)
    }
  }
  seen.delete(root)
  const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0)
  return [...seen]
    .map((id) => packages.get(id))
    .sort((a, b) => byCodePoint(a.name, b.name) || a.version.localeCompare(b.version, 'en', { numeric: true }))
}

/** I file di licenza pubblicati con un crate (LICENSE*, COPYING*, NOTICE*, piu' `license-file` del manifest). */
export function licenseTexts(pkg) {
  const directory = dirname(pkg.manifest_path)
  const names = new Set(
    readdirSync(directory).filter((name) => LICENSE_FILE.test(name) && statSync(join(directory, name)).isFile())
  )
  if (pkg.license_file) names.add(pkg.license_file.replaceAll('\\', '/'))
  return [...names]
    .sort()
    .map((name) => normalizeText(readFileSync(resolve(directory, name), 'utf8')))
    .filter((text) => text.length > 0)
}

export function renderLicenses({ fingerprint, notices, ofl, packages }) {
  const crateLabel = (pkg) => `${pkg.name} ${pkg.version}`
  const groups = new Map()
  const withoutFiles = []
  for (const pkg of packages) {
    const texts = pkg.texts ?? []
    if (texts.length === 0) withoutFiles.push(pkg)
    for (const text of texts) {
      if (!groups.has(text)) groups.set(text, [])
      groups.get(text).push(crateLabel(pkg))
    }
  }
  const lines = [
    'RocketLauncher - third-party licenses',
    '',
    `Inputs: sha256 ${fingerprint} (${licenseInputs.join(', ')}); Rust target ${rustTarget}.`,
    'Generated by scripts/rust-licenses.mjs (npm run licenses). Do not edit by hand.',
    '',
    'RocketLauncher itself is distributed under the GNU General Public License, version 3 (see LICENSE and',
    'NOTICE.md). The material below is by other authors and keeps its own license.',
    '',
    RULE,
    'PART 1 - USER INTERFACE (fonts and icons)',
    RULE,
    '',
    notices,
    '',
    RULE,
    'SIL Open Font License 1.1 (Inter, src/assets/fonts/OFL.txt)',
    RULE,
    '',
    ofl,
    '',
    RULE,
    `PART 2 - RUST CRATES COMPILED INTO RocketLauncher.exe (${packages.length})`,
    RULE,
    '',
    ...packages.map((pkg) => `${crateLabel(pkg)} - ${pkg.license ?? 'see license text'}${pkg.repository ? ` - ${pkg.repository}` : ''}`),
    ''
  ]
  if (withoutFiles.length > 0) {
    lines.push(
      'These crates ship no license file in their package: the license declared in their Cargo.toml applies, with',
      'their authors as copyright holders. The standard text of each of these licenses is reproduced below, where',
      'other crates publish it.',
      '',
      ...withoutFiles.map((pkg) => `${crateLabel(pkg)} - ${pkg.license ?? '?'} - ${(pkg.authors ?? []).join(', ') || 'authors not listed'}`),
      ''
    )
  }
  for (const [text, crates] of groups) {
    lines.push(RULE, `Used by: ${crates.join(', ')}`, RULE, '', text, '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

export function generate(root) {
  const metadata = JSON.parse(
    execFileSync(
      'cargo',
      ['metadata', '--format-version', '1', '--locked', '--filter-platform', rustTarget],
      { cwd: join(root, 'src-tauri'), encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 }
    )
  )
  const packages = runtimePackages(metadata).map((pkg) => ({ ...pkg, texts: licenseTexts(pkg) }))
  // Le note dall'elenco del materiale in poi: l'introduzione rimanda a questo stesso file.
  const allNotices = normalizeText(readFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), 'utf8'))
  const notices = allNotices.slice(Math.max(0, allNotices.indexOf('\n## ') + 1))
  const ofl = normalizeText(readFileSync(join(root, 'src/assets/fonts/OFL.txt'), 'utf8'))
  return renderLicenses({ fingerprint: inputsFingerprint(root), notices, ofl, packages })
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = join(import.meta.dirname, '..')
  try {
    const text = generate(root)
    writeFileSync(join(root, licensesFile), text)
    console.log(`${licensesFile}: ${text.length} caratteri.`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
